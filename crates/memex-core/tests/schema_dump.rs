//! App schema fixture (WI #3, architect D20).
//!
//! Builds a fresh vault in a temp dir and dumps its schema as plain SQL that the
//! app's `FakeVaultDb` loads into an in-memory `sqlite3` database. The dump holds
//! `sqlite_master.sql` for tables (first) and indexes (second), each group sorted
//! by name, followed by the `schema_version` rows and the `vault_settings` rows.
//! FTS5 virtual tables and their shadow tables (`chunk_fts*`), `chunk_vec` and
//! `sqlite_*` internals are excluded so the dump loads without extensions.
//!
//! The committed file must equal the dump byte for byte. Regenerate it with:
//!
//! ```sh
//! MEMEX_BLESS=1 cargo test -p memex-core --test schema_dump
//! ```

use std::fs;
use std::path::{Path, PathBuf};

use memex_core::Vault;
use rusqlite::Connection;

const BLESS_ENV: &str = "MEMEX_BLESS";

fn fixture_path() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../app/test/fixtures/vault_schema_v5.sql")
}

fn sql_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', "''"))
}

/// Deterministic, extension-free schema dump of `conn`.
fn dump_schema(conn: &Connection) -> String {
    let mut out = String::new();
    out.push_str("-- Generated by crates/memex-core/tests/schema_dump.rs from a fresh vault.\n");
    out.push_str(
        "-- Do not edit. Regenerate: MEMEX_BLESS=1 cargo test -p memex-core --test schema_dump\n\n",
    );

    let mut stmt = conn
        .prepare(
            "SELECT sql FROM sqlite_master
             WHERE type IN ('table', 'index')
               AND sql IS NOT NULL
               AND sql NOT LIKE 'CREATE VIRTUAL TABLE%'
               AND name NOT LIKE 'sqlite~_%' ESCAPE '~'
               AND name NOT LIKE 'chunk~_fts%' ESCAPE '~'
               AND name NOT LIKE 'chunk~_vec%' ESCAPE '~'
               AND tbl_name NOT LIKE 'chunk~_fts%' ESCAPE '~'
               AND tbl_name NOT LIKE 'chunk~_vec%' ESCAPE '~'
             ORDER BY CASE type WHEN 'table' THEN 0 ELSE 1 END, name",
        )
        .unwrap();
    let ddl: Vec<String> = stmt
        .query_map([], |r| r.get::<_, String>(0))
        .unwrap()
        .map(|r| r.unwrap())
        .collect();
    for sql in ddl {
        out.push_str(&sql);
        out.push_str(";\n\n");
    }

    let mut stmt = conn
        .prepare("SELECT version FROM schema_version ORDER BY version")
        .unwrap();
    let versions: Vec<i64> = stmt
        .query_map([], |r| r.get(0))
        .unwrap()
        .map(|r| r.unwrap())
        .collect();
    for v in versions {
        out.push_str(&format!(
            "INSERT INTO schema_version(version) VALUES ({v});\n"
        ));
    }

    let mut stmt = conn
        .prepare("SELECT key, value FROM vault_settings ORDER BY key")
        .unwrap();
    let settings: Vec<(String, String)> = stmt
        .query_map([], |r| Ok((r.get(0)?, r.get(1)?)))
        .unwrap()
        .map(|r| r.unwrap())
        .collect();
    for (k, v) in settings {
        out.push_str(&format!(
            "INSERT INTO vault_settings(key, value) VALUES ({}, {});\n",
            sql_quote(&k),
            sql_quote(&v)
        ));
    }
    out
}

/// Dump of a brand-new vault, which must be at schema V5.
fn fresh_v5_vault_dump() -> String {
    let dir = tempfile::tempdir().unwrap();
    let vault = Vault::create(dir.path().join("vault")).expect("create fresh vault");
    assert_eq!(
        vault.schema_version(),
        5,
        "a fresh vault must be at schema V5 for the v5 fixture"
    );
    dump_schema(vault.connection_ref())
}

/// Compare `dump` to the file at `path`, or (re)write the file when `bless`.
fn check_or_bless(dump: &str, path: &Path, bless: bool) -> Result<(), String> {
    if bless {
        let parent = path.parent().expect("fixture path has a parent");
        fs::create_dir_all(parent).map_err(|e| format!("create {}: {e}", parent.display()))?;
        // Write-then-rename so a concurrent reader never sees a partial file.
        let tmp = path.with_extension("sql.tmp");
        fs::write(&tmp, dump).map_err(|e| format!("write {}: {e}", tmp.display()))?;
        fs::rename(&tmp, path).map_err(|e| format!("rename to {}: {e}", path.display()))?;
        return Ok(());
    }
    let committed = fs::read_to_string(path).map_err(|e| {
        format!(
            "cannot read {}: {e}. Generate it with {BLESS_ENV}=1 cargo test -p memex-core --test schema_dump",
            path.display()
        )
    })?;
    if committed == dump {
        return Ok(());
    }
    let line = committed
        .lines()
        .zip(dump.lines())
        .position(|(a, b)| a != b)
        .unwrap_or_else(|| committed.lines().count().min(dump.lines().count()))
        + 1;
    Err(format!(
        "{} differs from a fresh vault's schema dump (first difference at line {line}). \
         Regenerate it with {BLESS_ENV}=1 cargo test -p memex-core --test schema_dump",
        path.display()
    ))
}

fn bless_requested() -> bool {
    std::env::var(BLESS_ENV).map(|v| v == "1").unwrap_or(false)
}

/// The committed fixture (or, during a bless run, the dump about to be written).
fn committed_fixture() -> String {
    if bless_requested() {
        return fresh_v5_vault_dump();
    }
    fs::read_to_string(fixture_path()).unwrap_or_else(|e| {
        panic!(
            "cannot read {}: {e}. Generate it with {BLESS_ENV}=1 cargo test -p memex-core --test schema_dump",
            fixture_path().display()
        )
    })
}

#[test]
fn committed_app_fixture_matches_fresh_v5_vault_dump() {
    let dump = fresh_v5_vault_dump();
    if let Err(e) = check_or_bless(&dump, &fixture_path(), bless_requested()) {
        panic!("{e}");
    }
}

#[test]
fn schema_dump_check_fails_when_fixture_differs() {
    let dump = fresh_v5_vault_dump();
    let dir = tempfile::tempdir().unwrap();
    let path = dir.path().join("vault_schema_v5.sql");

    fs::write(&path, &dump).unwrap();
    assert_eq!(check_or_bless(&dump, &path, false), Ok(()));

    let drifted = dump.replacen("smart_folders", "smart_folderz", 1);
    assert_ne!(drifted, dump, "dump must mention smart_folders");
    fs::write(&path, &drifted).unwrap();
    let err = check_or_bless(&dump, &path, false).expect_err("a drifted fixture must fail");
    assert!(
        err.contains(BLESS_ENV),
        "error must say how to regenerate: {err}"
    );

    fs::write(&path, format!("{dump}\n")).unwrap();
    assert!(
        check_or_bless(&dump, &path, false).is_err(),
        "a trailing-newline difference must fail (byte-for-byte)"
    );

    fs::remove_file(&path).unwrap();
    let err = check_or_bless(&dump, &path, false).expect_err("a missing fixture must fail");
    assert!(err.contains(BLESS_ENV), "{err}");
}

#[test]
fn schema_dump_bless_rewrites_the_fixture_file() {
    let dump = fresh_v5_vault_dump();
    let dir = tempfile::tempdir().unwrap();
    let path = dir.path().join("fixtures").join("vault_schema_v5.sql");

    // Missing file and parent dir: bless creates both.
    check_or_bless(&dump, &path, true).expect("bless writes the fixture");
    assert_eq!(fs::read_to_string(&path).unwrap(), dump);

    // Stale file: bless overwrites it, after which the check passes.
    fs::write(&path, "-- stale\n").unwrap();
    check_or_bless(&dump, &path, true).expect("bless overwrites a stale fixture");
    assert_eq!(fs::read_to_string(&path).unwrap(), dump);
    assert_eq!(check_or_bless(&dump, &path, false), Ok(()));
}

#[test]
fn committed_app_fixture_excludes_fts_and_vec_and_ends_with_seed_rows() {
    let fixture = committed_fixture();

    for banned in [
        "chunk_fts",
        "chunk_vec",
        "VIRTUAL",
        "sqlite_",
        "fts5",
        "vec0",
    ] {
        assert!(
            !fixture.contains(banned),
            "fixture must not mention {banned:?} (needs an extension the app's sqlite3 lacks)"
        );
    }

    let tail: Vec<&str> = fixture
        .lines()
        .filter(|l| !l.trim().is_empty())
        .rev()
        .take(6)
        .collect::<Vec<_>>()
        .into_iter()
        .rev()
        .collect();
    assert_eq!(
        tail,
        [
            "INSERT INTO schema_version(version) VALUES (1);",
            "INSERT INTO schema_version(version) VALUES (2);",
            "INSERT INTO schema_version(version) VALUES (3);",
            "INSERT INTO schema_version(version) VALUES (4);",
            "INSERT INTO schema_version(version) VALUES (5);",
            "INSERT INTO vault_settings(key, value) VALUES ('smart_folder_max_depth', '2');",
        ]
    );
    assert!(fixture.ends_with('\n'));
}

#[test]
fn committed_app_fixture_loads_into_a_plain_sqlite_database() {
    let fixture = committed_fixture();
    let conn = Connection::open_in_memory().unwrap();
    conn.execute_batch(&fixture)
        .expect("fixture loads as-is (tables before indexes, no extensions)");

    let tables: Vec<String> = {
        let mut stmt = conn
            .prepare("SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY name")
            .unwrap();
        let rows = stmt.query_map([], |r| r.get::<_, String>(0)).unwrap();
        rows.map(|r| r.unwrap()).collect()
    };
    for t in [
        "notes",
        "chunks",
        "links",
        "tags",
        "canvases",
        "canvas_nodes",
        "blocks",
        "day_reviews",
        "day_review_blocks",
        "footer_chips",
        "agent_changes",
        "smart_folders",
        "smart_folder_members",
        "vault_settings",
    ] {
        assert!(
            tables.iter().any(|x| x == t),
            "fixture lacks table {t}: {tables:?}"
        );
    }
    let max: i64 = conn
        .query_row("SELECT MAX(version) FROM schema_version", [], |r| r.get(0))
        .unwrap();
    assert_eq!(max, 5);
    let depth: String = conn
        .query_row(
            "SELECT value FROM vault_settings WHERE key = 'smart_folder_max_depth'",
            [],
            |r| r.get(0),
        )
        .unwrap();
    assert_eq!(depth, "2");
    let daily_index: i64 = conn
        .query_row(
            "SELECT COUNT(*) FROM sqlite_master WHERE type = 'index' AND name = 'idx_notes_daily_title'",
            [],
            |r| r.get(0),
        )
        .unwrap();
    assert_eq!(daily_index, 1);
    let chunk_cols: Vec<String> = {
        let mut stmt = conn
            .prepare("SELECT name FROM pragma_table_info('chunks') ORDER BY cid")
            .unwrap();
        let rows = stmt.query_map([], |r| r.get::<_, String>(0)).unwrap();
        rows.map(|r| r.unwrap()).collect()
    };
    assert!(
        chunk_cols.iter().any(|c| c == "start_byte"),
        "{chunk_cols:?}"
    );
    assert!(chunk_cols.iter().any(|c| c == "end_byte"), "{chunk_cols:?}");
}
