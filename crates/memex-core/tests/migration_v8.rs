fn open(db_path: &Path) -> Connection {
    let conn = Connection::open(db_path).unwrap();
    conn.pragma_update(None, "foreign_keys", "ON").unwrap();
    conn
}

/// Build a vault DB pinned at schema V7, with rows in it.
fn make_v7_db(dir: &Path) -> PathBuf {
    let db_path = dir.join("memex.db");
    let conn = Connection::open(&db_path).unwrap();
    conn.pragma_update(None, "journal_mode", "WAL").unwrap();
    conn.pragma_update(None, "foreign_keys", "ON").unwrap();
    conn.execute_batch(V7_DDL).unwrap();
    conn.execute_batch(V7_FTS).unwrap();
    conn.execute_batch(&v7_rows()).unwrap();
    assert_eq!(
        schema::current_version(&conn).unwrap(),
        7,
        "fixture: pinned at V7"
    );
    assert!(
        !has_column(&conn, "notes", "agent_read_only"),
        "fixture: a V7 notes table has no agent_read_only"
    );
    drop(conn);
    db_path
}

/// The V7 fixture after one `schema::apply`, asserted to have reached V8.
fn migrated_v7_fixture() -> (tempfile::TempDir, Connection) {
    let dir = tempfile::tempdir().unwrap();
    let db_path = make_v7_db(dir.path());
    let mut conn = open(&db_path);
    schema::apply(&mut conn).expect("V7 -> V8 migration succeeds");
    assert_eq!(
        schema::current_version(&conn).unwrap(),
        8,
        "schema::apply did not advance the V7 fixture to V8"
    );
    (dir, conn)
}

